"""All identity settings, nested by concern. Every environment variable is prefixed
``SMARTCOURSE_`` and nested groups are joined with ``__``, e.g.
``SMARTCOURSE_REDIS__URL=redis://localhost:6379/0`` sets ``settings.redis.url``.

Read from this service's own ``.env`` (``services/identity/.env``) — never another
service's.

``get_settings()`` is called eagerly at app startup (not lazily on first request) so a
misconfigured deployment fails before it accepts traffic.
"""

from functools import lru_cache

from pydantic import Field
from pydantic_settings import BaseSettings, SettingsConfigDict

from platform_core.config import (
    AppSettings,
    CorsSettings,
    HealthSettings,
    JWTVerifySettings,
    LogSettings,
    PostgresSettings,
    RedisSettings,
)


class IdentityAppSettings(AppSettings):
    service_name: str = "identity"
    port: int = 8001


class IdentityPostgresSettings(PostgresSettings):
    dsn: str = "postgresql+asyncpg://postgres:postgres@localhost:5432/identity_db"


class IdentityRedisSettings(RedisSettings):
    # DB 0: the auth keys the monolith already wrote (denylist, lockouts, reset
    # tokens) live here, so they stay valid across the split.
    url: str = "redis://localhost:6379/0"


class SecuritySettings(JWTVerifySettings):
    # Dev keys are generated by `make keys` into the repo-root secrets/ directory,
    # which is gitignored — never committed, never defaulted to a real key. Relative
    # paths resolve from services/identity/, where the service runs.
    jwt_private_key_path: str = "../../secrets/jwt_private.pem"
    jwt_kid: str = "dev-1"
    access_token_expires_minutes: int = 15
    refresh_token_expires_days: int = 30
    password_reset_token_expires_minutes: int = 30
    failed_login_max_attempts: int = 5
    failed_login_lockout_seconds: int = 300
    register_throttle_per_hour: int = 10


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_prefix="SMARTCOURSE_",
        env_nested_delimiter="__",
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
    )

    app: IdentityAppSettings = Field(default_factory=IdentityAppSettings)
    log: LogSettings = Field(default_factory=LogSettings)
    cors: CorsSettings = Field(default_factory=CorsSettings)
    postgres: IdentityPostgresSettings = Field(default_factory=IdentityPostgresSettings)
    redis: IdentityRedisSettings = Field(default_factory=IdentityRedisSettings)
    health: HealthSettings = Field(default_factory=HealthSettings)
    security: SecuritySettings = Field(default_factory=SecuritySettings)


@lru_cache
def get_settings() -> Settings:
    return Settings()
